//! OpenType Layout **language system tags** — the registered
//! vocabulary from the staged registry
//! (`docs/text/opentype/registries/language-tags.html`,
//! OpenType 1.9.1).
//!
//! A language system is "a set of typographic conventions for how
//! text in a given script should be presented" — tags do **not**
//! correspond one-to-one with languages: one set of conventions may
//! serve several languages, one language may have several convention
//! sets, and registration is perceived-need-based. Where a
//! correlation with languages exists, the registry documents it via
//! ISO 639 identifiers (individual languages from Set 3 or
//! collections from Set 2), which [`language_tags_for_iso639`]
//! searches.
//!
//! Registered tags are three or four capital letters (with a few
//! digit-suffixed exceptions such as `HAI0`/`PLG0`), space-padded to
//! four bytes. The tags `dflt` and `DFLT` are **permanently
//! reserved** as language system tags and must never appear in a
//! font's LangSysRecords: default data lives in each Script table's
//! default LangSys slot, which involves no tag at all.

