/// Whether `tag` is a registered language system tag.
pub fn is_registered_language_tag(tag: [u8; 4]) -> bool {
    REGISTERED_LANGUAGE_TAGS.iter().any(|(_, t, _)| *t == tag)
}

/// The registry name for a language system tag (tags are unique in
/// the registry).
pub fn language_tag_name(tag: [u8; 4]) -> Option<&'static str> {
    REGISTERED_LANGUAGE_TAGS
        .iter()
        .find(|(_, t, _)| *t == tag)
        .map(|(n, _, _)| *n)
}

/// Every language system tag whose registry annotation lists the
/// given ISO 639 identifier (case-insensitive exact ID match within
/// the comma-separated list), in registry order. More than one tag
/// may serve a language (e.g. `hai` appears under both `HAI ` and
/// `HAI0`), and a tag may list several IDs.
pub fn language_tags_for_iso639(iso639: &str) -> Vec<[u8; 4]> {
    REGISTERED_LANGUAGE_TAGS
        .iter()
        .filter(|(_, _, ids)| {
            ids.split(',')
                .map(str::trim)
                .any(|id| id.eq_ignore_ascii_case(iso639))
        })
        .map(|(_, t, _)| *t)
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn registry_shape_and_lookups() {
        // 661 rows transcribed from the registry; tags are unique.
        assert_eq!(REGISTERED_LANGUAGE_TAGS.len(), 661);
        for w in REGISTERED_LANGUAGE_TAGS.windows(1) {
            let (name, tag, _) = w[0];
            assert!(!name.is_empty());
            // Three or four capitals (or a digit suffix), space-padded.
            assert!(
                tag.iter()
                    .all(|b| b.is_ascii_uppercase() || b.is_ascii_digit() || *b == b' '),
                "{name}"
            );
        }
        let tags: Vec<[u8; 4]> = REGISTERED_LANGUAGE_TAGS
            .iter()
            .map(|(_, t, _)| *t)
            .collect();
        let mut dedup = tags.clone();
        dedup.sort_unstable();
        dedup.dedup();
        assert_eq!(dedup.len(), tags.len());

        assert!(is_registered_language_tag(*b"ENG "));
        assert!(is_registered_language_tag(*b"HO  "));
        assert!(is_registered_language_tag(*b"HAI0"));
        // dflt/DFLT are reserved, never registered.
        assert!(!is_registered_language_tag(*b"DFLT"));
        assert!(!is_registered_language_tag(*b"dflt"));

        assert_eq!(language_tag_name(*b"ENG "), Some("English"));
        assert_eq!(language_tag_name(*b"JAN "), Some("Japanese"));
        assert_eq!(language_tag_name(*b"ZHS "), Some("Chinese, Simplified"));
        assert_eq!(language_tag_name(*b"zzzz"), None);
    }

    #[test]
    fn iso639_reverse_lookup() {
        // The registry's Japanese row lists jpn.
        assert_eq!(language_tags_for_iso639("jpn"), vec![*b"JAN "]);
        // hai is listed under both HAI (via collection) and HAI0.
        let hai = language_tags_for_iso639("hai");
        assert!(hai.contains(b"HAI0"), "{hai:?}");
        // Multi-ID row: hax is one of HAI0's IDs.
        assert!(language_tags_for_iso639("hax").contains(b"HAI0"));
        // Case-insensitive; unknown IDs yield nothing.
        assert_eq!(
            language_tags_for_iso639("JPN"),
            language_tags_for_iso639("jpn")
        );
        assert!(language_tags_for_iso639("qqq").is_empty());
        // German: deu listed under DEU.
        assert!(language_tags_for_iso639("deu").contains(b"DEU "));
    }
}
